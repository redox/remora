import Foundation
import Testing
@testable import Capture

final class FakePasteboard: PasteboardReading, @unchecked Sendable {
    private let lock = NSLock()
    private var _changeCount: Int
    private var _string: String?
    private var _types: [String]

    init(changeCount: Int, string: String?, types: [String] = ["public.utf8-plain-text"]) {
        _changeCount = changeCount; _string = string; _types = types
    }
    var changeCount: Int { lock.withLock { _changeCount } }
    func string() -> String? { lock.withLock { _string } }
    func types() -> [String] { lock.withLock { _types } }
    func set(changeCount: Int, string: String? = nil, types: [String]? = nil) {
        lock.withLock {
            _changeCount = changeCount
            if let string { _string = string }
            if let types { _types = types }
        }
    }
}

final class Received: @unchecked Sendable {
    private let lock = NSLock()
    private var _texts: [String] = []
    var texts: [String] { lock.withLock { _texts } }
    func append(_ t: String) { lock.withLock { _texts.append(t) } }
}

@Test func firesOnceOnChange() {
    let pb = FakePasteboard(changeCount: 1, string: "hello")
    let got = Received()
    let w = ClipboardWatcher(pasteboard: pb, onText: { got.append($0) })
    w.poll()                       // 1: baseline taken at init, unchanged
    w.poll()                       // 1: still unchanged
    pb.set(changeCount: 2)
    w.poll()                       // 2: changed
    w.poll()                       // 2: unchanged again
    #expect(got.texts == ["hello"])
}

@Test func ignoresConcealedAndTransient() {
    let pb = FakePasteboard(changeCount: 1, string: "s3cret-password")
    let got = Received()
    let w = ClipboardWatcher(pasteboard: pb, onText: { got.append($0) })
    pb.set(changeCount: 2, types: ["org.nspasteboard.ConcealedType", "public.utf8-plain-text"])
    w.poll()
    pb.set(changeCount: 3, types: ["org.nspasteboard.TransientType", "public.utf8-plain-text"])
    w.poll()
    pb.set(changeCount: 4, types: ["public.utf8-plain-text", "org.nspasteboard.AutoGeneratedType"])
    w.poll()
    #expect(got.texts.isEmpty)
}

@Test func ignoresNonText() {
    let pb = FakePasteboard(changeCount: 1, string: nil, types: ["public.png"])
    let got = Received()
    let w = ClipboardWatcher(pasteboard: pb, onText: { got.append($0) })
    pb.set(changeCount: 2)
    w.poll()
    #expect(got.texts.isEmpty)
}

@Test func ignoresWhitespaceOnlyText() {
    let pb = FakePasteboard(changeCount: 1, string: "  \n\t ")
    let got = Received()
    let w = ClipboardWatcher(pasteboard: pb, onText: { got.append($0) })
    pb.set(changeCount: 2)
    w.poll()
    #expect(got.texts.isEmpty)
}

@Test func concealedChangeIsConsumedNotReplayed() {
    // A concealed copy followed by no further change must not fire later.
    let pb = FakePasteboard(changeCount: 1, string: "pw",
                            types: ["org.nspasteboard.ConcealedType", "public.utf8-plain-text"])
    let got = Received()
    let w = ClipboardWatcher(pasteboard: pb, onText: { got.append($0) })
    pb.set(changeCount: 2)
    w.poll()
    pb.set(changeCount: 2, types: ["public.utf8-plain-text"])
    w.poll()
    #expect(got.texts.isEmpty)
}

/// Simulates a new item (e.g. a concealed password) landing while `string()` is being read.
final class RacingPasteboard: PasteboardReading, @unchecked Sendable {
    private let lock = NSLock()
    private var _changeCount = 1
    private var _types = ["public.utf8-plain-text"]
    private var _string = "first"
    private let raceTypes: [String]
    private let raceString: String
    private var raced = false

    init(raceTypes: [String], raceString: String) {
        self.raceTypes = raceTypes; self.raceString = raceString
    }
    var changeCount: Int { lock.withLock { _changeCount } }
    func types() -> [String] { lock.withLock { _types } }
    func string() -> String? {
        lock.withLock {
            let value = _string
            if !raced, _changeCount == 2 {  // the copy we are reading is replaced mid-read
                raced = true
                _changeCount = 3; _types = raceTypes; _string = raceString
                return raceString           // the reader sees the new item's string
            }
            return value
        }
    }
    func bump() { lock.withLock { _changeCount = 2; _string = "second" } }
}

@Test func concealedItemLandingDuringReadIsNotFired() {
    let pb = RacingPasteboard(raceTypes: ["org.nspasteboard.ConcealedType", "public.utf8-plain-text"],
                              raceString: "hunter2")
    let got = Received()
    let w = ClipboardWatcher(pasteboard: pb, onText: { got.append($0) })
    pb.bump()
    let first = w.poll()   // changeCount moved during string(): dropped
    let second = w.poll()  // the racing item is now seen with its own (concealed) types
    #expect(first == nil && second == nil && got.texts.isEmpty)
}

@Test func plainItemLandingDuringReadIsFiredOnNextPoll() {
    let pb = RacingPasteboard(raceTypes: ["public.utf8-plain-text"], raceString: "third")
    let got = Received()
    let w = ClipboardWatcher(pasteboard: pb, onText: { got.append($0) })
    pb.bump()
    w.poll()
    let next = w.poll()
    #expect(next == "third" && got.texts == ["third"])
}
