    // MARK: Tools

    func chronicle(_ a: Args) throws -> JSONValue {
        let raw = try a.string("level", required: true) ?? ""
        guard let level = ChronicleLevel(rawValue: raw) else {
            throw ArgumentError(message: "level must be one of hour, day, week, month, year.")
        }
        let date = try a.int("date").map(Self.date) ?? Date()
        let count = min(max(try a.int("count") ?? 1, 1), Self.maxChronicleCount)
        let db = try openMemory()
        let policy = SnapshotPolicy.current(db)
        let component = level.calendarComponent
        guard let newest = calendar.dateInterval(of: component, for: date) else { return .array([]) }
        let oldest = calendar.date(byAdding: component, value: -(count - 1), to: newest.start) ?? newest.start
        let rows = try ChronicleStore(db).list(level: level, from: oldest, to: newest.end).reversed()
        return try db.reader.read { d in
            let allowed = try DerivedPolicy.filter(Array(rows), ids: \.snapshotIDs, policy: policy, in: d)
            return .array(try allowed.prefix(count).map { try Self.chronicleValue($0, in: d) })
        }
    }

    func workingMemory(_ a: Args) throws -> JSONValue {
        let limit = try a.limit(default: Self.defaultWorkingMemoryLimit)
        let db = try openMemory()
        let policy = SnapshotPolicy.current(db)
        let now = Date()
        return try db.reader.read { d in
            try Self.workingMemoryValues(limit, now: now, policy: policy, db: db, in: d)
        }
    }

    func attentionContext(_ a: Args) throws -> JSONValue {
        let db = try openMemory()
        let policy = SnapshotPolicy.current(db)
        let now = Date()
        let events = try Self.allowedEvents(since: now.addingTimeInterval(-Self.attentionWindow), policy: policy, db: db)
            .suffix(Self.attentionActivityMax)
        let flags = SalientFlagStore(db)
        let due = try flags.dueSoon(within: Self.openItemsDueWithin, now: now, limit: 50)
        let seen = try flags.open(kinds: Set(FlagKind.allCases), limit: 500)
            .filter { $0.lastSeenAt >= now.addingTimeInterval(-Self.openItemsSeenWithin) }
            .sorted { $0.lastSeenAt > $1.lastSeenAt }
        var ids = Set<Int64>(), candidates: [SalientFlag] = []
        for f in due + seen { if let id = f.id, ids.insert(id).inserted { candidates.append(f) } }
        return try db.reader.read { d in
            // The digest cites no snapshot: under `.denyAll` it is withheld like every derived row,
            // and after a forget until a rebuild is stored (`ForgetMarks`).
            let digest = policy.deniesEverything || ForgetMarks.digestIsDirty(in: d) ? nil
                : try MemoryDigest.fetchOne(d, sql: "SELECT * FROM memory_digest ORDER BY id DESC LIMIT 1")
            let hours = try Chronicle.fetchAll(d, sql: """
                SELECT * FROM chronicle WHERE level = ? AND period_start <= ? ORDER BY period_start DESC, id DESC LIMIT 24
                """, arguments: [ChronicleLevel.hour.rawValue, now])
            let latest = try DerivedPolicy.filter(hours, ids: \.snapshotIDs, policy: policy, in: d).first
            let items = Array(try DerivedPolicy.filter(candidates, ids: \.snapshotIDs, policy: policy, in: d)
                .prefix(Self.openItemsMax))
            let visible = try Self.allowedSnapshotIDs(items.flatMap(\.snapshotIDs), policy: policy, in: d)
            return .object([
                "now": .int(Self.seconds(now)),
                "activity": .array(events.map(Self.eventValue)),
                "working_memory": try Self.workingMemoryValues(Self.attentionWorkingMemory, now: now, policy: policy,
                                                               db: db, in: d),
                "latest_hour": try latest.map { try Self.chronicleValue($0, in: d) } ?? .null,
                "open_items": .array(try items.map { f in
                    .object([
                        "kind": .string(f.kind.rawValue), "text": .string(f.text), "person": .string(f.person),
                        "project": .string(f.project), "due_at": f.dueAt.map { .int(Self.seconds($0)) } ?? .null,
                        "status": .string(f.status.rawValue), "snapshot_ids": Self.ids(f.snapshotIDs, visible: visible),
                        "generated_by": try Self.generatedBy(f.llmCallID, in: d),
                    ])
                }),
                "digest": try digest.map { g in
                    .object(["text": .string(String(g.body.prefix(Self.digestLimit))),
                             "generated_by": try Self.generatedBy(g.llmCallID, in: d)])
                } ?? .null,
            ])
        }
    }

    func searchWiki(_ a: Args) async throws -> JSONValue {
        let query = try a.string("query", required: true) ?? ""
        let type = try Self.pageType(a.string("type"))
        let limit = try a.limit(default: Self.defaultWikiSearchLimit)
        let db = try openMemory()
        let policy = SnapshotPolicy.current(db)
        let embedder = await readyEmbedder()
        let search = HybridSearch(db: db, embedder: embedder, index: embedder == nil ? nil : VectorIndex(db: db),
                                  policy: { policy })
        let hits = try await search.search(query: query, terms: Self.wikiTerms(query), scopes: [.wikiPage, .wikiFact],
                                           limit: Self.wikiHitPool, policy: policy)
        // Facts count for their page: its best score, and the best fact that matched.
        var order: [String] = []
        var found: [String: (score: Double, fact: String?)] = [:]
        for hit in hits {
            guard let slug = hit.slug else { continue }
            let fact = hit.scope == .wikiFact ? hit.snippet : nil
            if var seen = found[slug] {
                if seen.fact == nil, let fact { seen.fact = fact; found[slug] = seen }
            } else {
                order.append(slug)
                found[slug] = (hit.score, fact)
            }
        }
        return try Self.wikiSearchRows(order, found: found, type: type, limit: limit, policy: policy, db: db)
    }

    /// The pages behind `slugs` (in order) that pass `type` and `policy`, with their search score
    /// and matched fact.
    private static func wikiSearchRows(_ slugs: [String], found: [String: (score: Double, fact: String?)],
                                       type: WikiPageType?, limit: Int, policy: CapturePolicy,
                                       db: AppDatabase) throws -> JSONValue {
        try db.reader.read { d in
            let pages = try slugs.compactMap { try WikiStore.page(slug: $0, in: d) }.filter { type == nil || $0.type == type }
            let allowed = try DerivedPolicy.filter(pages, ids: \.snapshotIDs, policy: policy, in: d).prefix(limit)
            return .array(try allowed.map { p in
                var row = try pageRow(p, in: d)
                row["score"] = .double(found[p.slug]?.score ?? 0)
                row["matched_fact"] = opt(found[p.slug]?.fact)
                return .object(row)
            })
        }
    }

    func wikiPage(_ a: Args) throws -> JSONValue {
        let slug = try a.string("slug", required: true) ?? ""
        let history = try a.bool("include_history") ?? false
        let db = try openMemory()
        let policy = SnapshotPolicy.current(db)
        return try db.reader.read { d in
            // A page hidden by the current exclusions answers like a missing one.
            guard let page = try WikiStore.page(slug: slug, in: d),
                  !(try DerivedPolicy.filter([page], ids: \.snapshotIDs, policy: policy, in: d)).isEmpty else {
                throw ArgumentError(message: Self.wikiPageNotFound)
            }
            let facts = try DerivedPolicy.filter(try WikiStore.facts(slug: slug, includeInvalid: history, in: d),
                                                 ids: \.snapshotIDs, policy: policy, in: d)
            let visible = try Self.allowedSnapshotIDs(facts.flatMap(\.snapshotIDs), policy: policy, in: d)
            let linked = try page.links.compactMap { try WikiStore.page(slug: $0, in: d) }
            let links = try DerivedPolicy.filter(linked, ids: \.snapshotIDs, policy: policy, in: d).map(\.slug)
            return .object([
                "slug": .string(page.slug), "type": .string(page.type.rawValue), "title": .string(page.title),
                "aliases": .array(page.aliases.map { .string($0) }), "summary": .string(page.summary),
                "body": .string(page.body), "links": .array(links.map { .string($0) }),
                "mention_count": .int(page.mentionCount), "first_seen": .int(Self.seconds(page.firstSeen)),
                "last_seen": .int(Self.seconds(page.lastSeen)),
                "facts": .array(try facts.map { f in
                    .object([
                        "id": .int(Int(f.id ?? 0)), "fact": .string(f.fact), "subject": .string(f.subject.rawValue),
                        "basis": .string(f.basis.rawValue), "worth": .string(f.worth.rawValue),
                        "valid_at": .int(Self.seconds(f.validAt)),
                        "invalid_at": f.invalidAt.map { .int(Self.seconds($0)) } ?? .null,
                        "snapshot_ids": Self.ids(f.snapshotIDs, visible: visible),
                        "generated_by": try Self.generatedBy(f.llmCallID, in: d),
                    ])
                }),
                "generated_by": try Self.generatedBy(page.llmCallID, in: d),
            ])
        }
    }

    func listWiki(_ a: Args) throws -> JSONValue {
        let type = try Self.pageType(a.string("type"))
        guard let sort = WikiSort(rawValue: try a.string("sort") ?? WikiSort.recent.rawValue) else {
            throw ArgumentError(message: "sort must be recent or mentions.")
        }
        let limit = try a.limit(default: Self.defaultWikiListLimit)
        let offset = max(try a.int("offset") ?? 0, 0)
        let db = try openMemory()
        let policy = SnapshotPolicy.current(db)
        let store = WikiStore(db)
        // The offset counts pages the caller can see, so hidden pages never shift the paging.
        let batch = 200
        var scanned = 0, skipped = 0
        var pages: [WikiPage] = []
        while pages.count < limit {
            let rows = try store.list(type: type, sort: sort, limit: batch, offset: scanned)
            scanned += rows.count
            let allowed = try db.reader.read { try DerivedPolicy.filter(rows, ids: \.snapshotIDs, policy: policy, in: $0) }
            for p in allowed where pages.count < limit {
                if skipped < offset { skipped += 1 } else { pages.append(p) }
            }
            if rows.count < batch { break }
        }
        return try db.reader.read { d in .array(try pages.map { .object(try Self.pageRow($0, in: d)) }) }
    }

    // MARK: Helpers

    /// The database, once it has the Plan 4 memory tables.
    private func openMemory() throws -> AppDatabase {
        let db = try open()
        let ready = try db.reader.read { d in try Self.memoryTables.allSatisfy { try d.tableExists($0) } }
        guard ready else { throw ArgumentError(message: Self.memoryNeedsUpdate) }
        return db
    }

    /// The embedder when its model is ready within `embedderTimeout`; nil means FTS only.
    private func readyEmbedder() async -> (any Embedder)? {
        guard let embedder = embedders.get() else { return nil }
        let ready = await TimeBound.run(within: embedderTimeout) {
            EmbeddingIndexer.usable(await embedder.identity()) != nil
        }
        return ready == true ? embedder : nil
    }

    /// The query's search terms; for a query of short words only (a name like "Li Wu"), those.
    static func wikiTerms(_ query: String) -> [String] {
        let terms = QueryTerms.extract(from: [query])
        guard terms.isEmpty else { return terms }
        var seen = Set<String>()
        return query.lowercased().components(separatedBy: CharacterSet.alphanumerics.inverted)
            .filter { $0.count >= 2 && $0.contains(where: \.isLetter) && seen.insert($0).inserted }
            .prefix(8).map { $0 }
    }

    private static func pageType(_ raw: String?) throws -> WikiPageType? {
        guard let raw else { return nil }
        guard let type = WikiPageType(rawValue: raw) else {
            throw ArgumentError(message: "type must be one of person, project, topic, tool, org.")
        }
        return type
    }

    /// `{model, backend, input_tokens, output_tokens, est_cost_usd, at}`, or null when there is no
    /// call row (never recorded, or deleted).
    static func generatedBy(_ callID: Int64?, in d: Database) throws -> JSONValue {
        guard let callID, let g = try LLMCallStore.generatedBy(callID: callID, in: d) else { return .null }
        return .object([
            "model": .string(g.model), "backend": .string(g.backend), "input_tokens": .int(g.inputTokens),
            "output_tokens": .int(g.outputTokens), "est_cost_usd": g.estCostUSD.map { .double($0) } ?? .null,
            "at": .int(seconds(g.at)),
        ])
    }

    /// `ids` in order, keeping only the allowed ones.
    private static func ids(_ ids: [Int64], visible: Set<Int64>) -> JSONValue {
        .array(ids.filter(visible.contains).map { .int(Int($0)) })
    }

    private static func chronicleValue(_ c: Chronicle, in d: Database) throws -> JSONValue {
        .object([
            "level": .string(c.level.rawValue), "period_key": .string(c.periodKey),
            "start": .int(seconds(c.periodStart)), "end": .int(seconds(c.periodEnd)),
            "summary": .string(String(c.summary.prefix(chronicleSummaryLimit))),
            "projects": .array(c.metadata.projects.map { .object(["name": .string($0.name), "share": .double($0.share)]) }),
            "highlights": .array(c.metadata.highlights.map { .string($0) }),
            "generated_by": try generatedBy(c.llmCallID, in: d),
        ])
    }

    private static func pageRow(_ p: WikiPage, in d: Database) throws -> [String: JSONValue] {
        [
            "slug": .string(p.slug), "type": .string(p.type.rawValue), "title": .string(p.title),
            "summary": .string(p.summary), "last_seen": .int(seconds(p.lastSeen)), "mention_count": .int(p.mentionCount),
            "generated_by": try generatedBy(p.llmCallID, in: d),
        ]
    }

    /// The `n` most relevant working-memory items alive now (seen within 24 h, decayed relevance
    /// ≥ 0.05) with at least one live, allowed snapshot (or none cited), as in the rewrite context.
    private static func workingMemoryValues(_ n: Int, now: Date, policy: CapturePolicy, db: AppDatabase,
                                            in d: Database) throws -> JSONValue {
        let alive = try WorkingMemoryStore(db).top(WorkingMemoryStore.maxItems, now: now, in: d).filter {
            now.timeIntervalSince($0.lastSeenAt) <= WorkingMemoryStore.maxAge
                && WorkingMemoryStore.decayed($0, now: now) >= WorkingMemoryStore.minRelevance
        }
        let items = Array(try DerivedPolicy.requiringLiveEvidence(alive, ids: \.snapshotIDs, policy: policy, in: d).prefix(n))
        let visible = try allowedSnapshotIDs(items.flatMap(\.snapshotIDs), policy: policy, in: d)
        return .array(try items.map { i in
            .object([
                "text": .string(i.text), "kind": .string(i.kind),
                "relevance": .double((WorkingMemoryStore.decayed(i, now: now) * 100).rounded() / 100),
                "last_seen_at": .int(seconds(i.lastSeenAt)), "snapshot_ids": ids(i.snapshotIDs, visible: visible),
                "generated_by": try generatedBy(i.llmCallID, in: d),
            ])
        })
    }
