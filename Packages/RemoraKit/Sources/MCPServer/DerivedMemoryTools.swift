                """ + derivedNotice,
            inputSchema: schema([
                "level": ["type": "string", "enum": ["hour", "day", "week", "month", "year"]],
                "date": ["type": "integer", "description": "Unix seconds inside the newest period, default now"],
                "count": ["type": "integer", "description": "Periods to walk back, default 1, max 24"],
            ], required: ["level"])),
        ToolDefinition(
            name: "get_working_memory",
            description: """
                What the user is in the middle of: short-lived threads from the last hours, most \
                relevant first (relevance decays with a 6-hour half-life). snapshot_ids can be read \
                with get_snapshots.
                """ + derivedNotice,
            inputSchema: schema([
                "limit": ["type": "integer", "description": "Max items, default 12, max 20"],
            ])),
        ToolDefinition(
            name: "get_attention_context",
            description: """
                One call to orient on the present: apps and windows focused in the last 15 minutes, \
                the top working memory, the latest hour summary, open items (commitments, to-dos and \
                events due within 7 days or seen in the last 48 hours) and the memory digest.
                """ + derivedNotice,
            inputSchema: schema([:])),
        ToolDefinition(
            name: "search_wiki",
            description: """
                Search the user's personal wiki (people, projects, topics, tools, organisations) built \
                from their screen history. Matches pages and their facts; matched_fact is the fact \
                that matched, if any. Read a page with get_wiki_page.
                """ + derivedNotice,
            inputSchema: schema([
                "query": ["type": "string", "description": "Words or a name to look for"],
                "type": ["type": "string", "enum": pageTypes],
                "limit": ["type": "integer", "description": "Max pages, default 10, max 20"],
            ], required: ["query"])),
        ToolDefinition(
            name: "get_wiki_page",
            description: """
